package com.ssafy.scenecrew.event.service;

import java.util.UUID;

/**
 * 행사 초대 토큰 자리. 발급·보관(암호화 저장)·회전은 초대 담당(S15P31A202-231)이 이 인터페이스의 빈으로 구현한다.
 * 공개 기능 사용 시 빈이 반드시 필요하며, 키 설정은 시작 시 검사한다.
 *
 * <p>토큰을 쓸 수 있는지는 행사 상태가 정한다. 모집 중·운영 중에만 참여를 받고 종료하면 막는다(참여 035의 상태 검사).
 * 공개 때 발급한 토큰을 바꾸지 않고, 시작한 뒤에도 같은 토큰을 쓴다.
 * 두 메서드 모두 행사 업무 트랜잭션 안에서 부른다. 실패하면 생성·공개 전체가 롤백된다.
 * 원문 토큰을 응답·요청 키 기록(receipt)에 넣지 않는다.
 */
public interface InviteTokens {
    /** 행사 생성(022) 때, 새 Event를 저장한 뒤 부른다. 이 행사의 초대 토큰을 만든다. */
    void issue(UUID eventId);

    /** 첫 공개(029) 때, 행사를 잠근 채 부른다. 토큰을 보존·검증한다. 두 값이 모두 없는 과거 DRAFT의 첫 공개만 발급한다. */
    void activate(UUID eventId);
}
